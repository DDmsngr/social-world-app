-- LEGAL-2: пока переписка выключена флагом, она должна быть выключена и на
-- сервере, а не только спрятана в интерфейсе.
--
-- Клиентский `Features.chat` прячет вкладку, но API отвечает всем: RLS
-- проверяет лишь участие в диалоге, а не то, включена ли функция. Любой, у
-- кого есть anon-ключ (он лежит в APK) и сессия, мог бы переписываться в
-- обход приложения. Для сервиса, у которого ещё не решён статус ОРИ, это
-- именно та деятельность, которой пока быть не должно.
--
-- Отзыва прав на таблицы недостаточно: create_direct_conversation объявлена
-- `security definer` и пишет от имени владельца, игнорируя гранты
-- вызывающей роли. Поэтому у неё отзывается право на выполнение.
--
-- Симметрия на будущее: когда статус ОРИ решён и чат включается, отдельная
-- миграция возвращает ровно эти четыре строки прав (см. 0003_chat.sql).

revoke execute on function create_direct_conversation(uuid) from authenticated;

-- Передача сообщений — то, что делает сервис мессенджером. Чтение своей
-- старой переписки не трогаем: данные и так принадлежат участникам, а
-- select-политики и без того пускают только их.
revoke insert on chat_messages from authenticated;

-- Публикация ключей шифрования — часть той же функции, без неё переписка
-- всё равно не начнётся.
revoke insert, update on chat_public_keys from authenticated;

