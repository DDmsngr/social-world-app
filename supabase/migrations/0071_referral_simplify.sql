-- Реферальная система проще: человек зарегистрировался по приглашению и
-- назвал себя при знакомстве — приглашающему сразу идут баллы. Раньше ждали
-- фото профиля и первого действия, а потом ещё проверку.
--
-- Что остаётся: антифрод (устройство, IP, подозрительные приглашения),
-- потолок баллов за одного приглашённого и лимит приглашений в день.
-- Начисление по-прежнему делает referrals_tick раз в минуту, поэтому баллы
-- приходят не мгновенно, а в течение минуты.

update referral_settings
set require_avatar = false,
    require_first_action = false,
    require_phone = false,
    hold_minutes = 0,
    updated_at = now();
