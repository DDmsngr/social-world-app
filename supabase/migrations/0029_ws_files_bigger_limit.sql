-- Голосовые и видео в чате панели команды крупнее обычных вложений — 25 МБ
-- (лимит бакета ws-files из 0017) хватает на пару минут голосового и почти
-- ничего на видео. Серверный предел self-hosted Storage — 250 МБ
-- (FILE_SIZE_LIMIT в docker-compose), так что поднимаем бакет до 100 МБ —
-- с запасом на короткое видео, но не настолько много, чтобы один файл
-- заметно нагружал диск ВМ.

update storage.buckets set file_size_limit = 104857600 where id = 'ws-files';
