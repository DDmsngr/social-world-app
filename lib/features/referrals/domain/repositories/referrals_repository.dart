/// Реферальные QR у мест (стикер в кафе → скачал → кассир отдал бонус на
/// глаз). Код нужен только для статистики «сколько установок принесло это
/// место» — сама награда через приложение не проверяется и не выдаётся.
abstract interface class ReferralsRepository {
  /// Записывает переход по коду. Идемпотентно: повторный вызов тем же
  /// человеком с тем же кодом ничего не меняет. Неизвестный код бросает
  /// исключение — вызывающая сторона показывает «код не найден».
  Future<void> recordSignup(String code);
}
