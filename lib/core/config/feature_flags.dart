import 'dev_mode.dart';

/// Функции, которые собраны, но не выходят в релиз.
abstract final class Features {
  /// Личные сообщения.
  ///
  /// Сервис с перепиской Роскомнадзор вправе признать организатором
  /// распространения информации: это год хранения сообщений на территории РФ
  /// и выдача ключей ФСБ по запросу. Риск остаётся открытым до регистрации
  /// ООО и разбора конфигурации юристом.
  ///
  /// 29.09: включено и в релизной сборке (`flutter-ci.yml`) по решению
  /// Алексея — на этом этапе аудитория только разработчики (внутреннее
  /// тестирование), не публичный запуск.
  ///
  /// Флаг: `--dart-define=FEATURE_CHAT=true`.
  static const _chatOverride = bool.fromEnvironment('FEATURE_CHAT');

  /// В dev-режиме чат работает на локальном репозитории без Supabase.
  static bool get chat => DevMode.enabled || _chatOverride;

  /// Видеоаватар (короткий кружок вместо фото). Механика готова — миграция
  /// 0044, запись только у премиума, — но показ закрыт, пока продукт не решил,
  /// когда и кому её открыть. Флаг: `--dart-define=FEATURE_VIDEO_AVATAR=true`.
  static const videoAvatar = bool.fromEnvironment('FEATURE_VIDEO_AVATAR');
}
